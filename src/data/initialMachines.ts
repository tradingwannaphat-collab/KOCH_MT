function getMachinePhoto(name: string, category: string, code: string): string {
  const n = name.toLowerCase();
  const c = code.toLowerCase();
  if (c.startsWith('fcu') || n.includes('fan coil')) return MACHINE_PHOTOS.fcu;
  if (c.startsWith('cdu') || n.includes('condensing')) return MACHINE_PHOTOS.cdu;
  if (n.includes('slot')) return MACHINE_PHOTOS.slot;
  if (n.includes('cutting')) return MACHINE_PHOTOS.cutting;
  if (n.includes('long way') || n.includes('flexo') || n.includes('print')) return MACHINE_PHOTOS.printing;
  if (n.includes('die cut')) return MACHINE_PHOTOS.diecut;
  if (n.includes('glued') || n.includes('gluing')) return MACHINE_PHOTOS.gluing;
  if (n.includes('stitching')) return MACHINE_PHOTOS.stitching;
  if (n.includes('centrifugal') || n.includes('tying')) return MACHINE_PHOTOS.tying;
  if (n.includes('wastewater')) return MACHINE_PHOTOS.wastewater;
  if (n.includes('air pump') || n.includes('compressor')) return MACHINE_PHOTOS.airpump;
  return MACHINE_PHOTOS.slot;
}

